import 'dart:io';

/// Платформа для навыка «Пароли»: что здесь можно и что честно сказать.
enum PasswordsPlatform {
  android,
  windows,
  macos,
  linux,
  other;

  static PasswordsPlatform get current {
    if (Platform.isAndroid) return android;
    if (Platform.isWindows) return windows;
    if (Platform.isMacOS) return macos;
    if (Platform.isLinux) return linux;
    return other;
  }

  /// Копировать пароль в буфер: на Windows и macOS — нет, пока нет канала
  /// без облачного буфера, истории и Handoff (D22, этап 4).
  bool get canCopySecrets => this != windows && this != macos;

  /// Честная строка о входе в сейф с мастер-паролем (сборки без ключа
  /// устройства).
  String get unlockNote => 'Сейф открывается мастер-паролем.';

  /// Честная строка о защите сейфа устройством на этой платформе
  /// (ADR-025). [pin], [bio] — что включено сейчас: тогда сказать, чем
  /// сейф открывается. [inSettings] — строка стоит в самих настройках
  /// сейфа: «включите … в настройках сейфа» там лишнее.
  String deviceNote({
    bool pin = false,
    bool bio = false,
    bool inSettings = false,
    bool codeOnly = false,
  }) {
    if (codeOnly) {
      return 'Сейф открывается только кодом восстановления: ключ телефона '
          'недоступен или ПИН-код закрыт после 10 ошибок. После входа '
          'защиту можно включить заново в настройках сейфа.';
    }
    if (pin || bio) {
      final by = pin && bio
          ? 'ПИН-кодом сейфа или отпечатком'
          : pin
              ? 'ПИН-кодом сейфа'
              : 'отпечатком или блокировкой экрана';
      return 'Сейф открывается $by; без ${pin && bio ? 'них' : 'него'} — '
          'кодом восстановления.';
    }
    return switch (this) {
      android => 'Сейф защищён ключом этого телефона и открывается сам, '
          'пока открыто приложение. Кто держит разблокированный телефон, '
          'откроет и сейф${inSettings ? '.' : ' — включите ПИН-код сейфа или '
              'вход по отпечатку в настройках сейфа.'}',
      windows => 'Сейф защищён учётной записью Windows: с другого '
          'компьютера или из другой учётной записи его не открыть.',
      macos ||
      linux ||
      other =>
        'На этом компьютере пароли защищены только вашей учётной записью: '
            'копия папки приложения целиком открывает сейф. Храните код '
            'восстановления отдельно.',
    };
  }

  /// Ключ устройства здесь — только файл (macOS, Linux): предупреждение
  /// на экране сейфа.
  bool get fileKeyOnly => this == macos || this == linux || this == other;

  /// Почему кнопки «Скопировать» у пароля нет.
  String? get copyNote => canCopySecrets
      ? null
      : 'Копирование паролей на этом компьютере появится позже: Windows и '
          'macOS могут отправить буфер обмена на другие устройства.';
}
