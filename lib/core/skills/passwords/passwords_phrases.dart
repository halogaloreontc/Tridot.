    _Rule(
      RegExp('^(?=.*$_pwOrSafe)(?:.*\\s)?'
          r'(?:тренировк|потренир|тренир)[а-яё]*\s+(?:\S+\s+){0,2}?памят[а-яё]*'
          r'(?:.*?\s(?:по|на|в)\s+(?:паролю|пароли|паролям|паролях)'
          r'(?:\s+(?:от|для|к)\s+(?<svc>.+))?)?'),
