          '(?=.*(?:$_deviceLoss|$_deviceMove))'),
      PasswordCommands.lostDevice,
      0.85,
    ),
    // Без слова о паролях — только с вопросом, как вернуть данные:
    // «Лиорио, потерял смартфон, как вернуть доступ к данным?». «Разбил
    // телефон, нужно купить новый» — не о сейфе.
