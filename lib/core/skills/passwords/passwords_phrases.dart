  /// её не получает ни один сетевой коннектор (раздел 5.9). Это и
  /// разобранная команда, и любое упоминание слова «пароль» ([mentions]).
  static bool looksLike(Utterance utterance) =>
      mentions(utterance) || parse(utterance) != null;

  /// Слово «пароль» в любой форме («пароли», «паролем», «мастер-пароль»),
  /// «password», «пасс».
  static final RegExp _mention = RegExp(
    r'(?<![a-zа-яё])(?:парол|password|пасс(?![a-zа-яё]))',
    caseSensitive: false,
  );

  /// Во фразе упомянут пароль — независимо от [parse]: «напомни мне
  /// сменить пароль» — задача, но сетевому коннектору её не показываем
  /// ни при какой уверенности, включён навык или нет.
  static bool mentions(Utterance utterance) =>
      _mention.hasMatch(utterance.normalized) ||
      _mention.hasMatch(utterance.original);

  /// Разбор [utterance] или `null` — не фраза о паролях.
  static PasswordCommand? parse(Utterance utterance) {
    final text = _prepare(utterance.normalized);
    if (text.isEmpty || !text.contains(_anchor)) return null;
    // Как написано (регистр): для названия сервиса, имён в [_foreign].
    final shown = _prepare(utterance.original);
    final aligned = shown.length == text.length;
    for (final rule in _rules) {
      final match = rule.pattern.firstMatch(text);
      if (match == null) continue;
      if (rule.when != null && !rule.when!(text, match)) continue;
      if (rule.statement && utterance.isQuestion) continue;
      final cmd = rule.cmdOf?.call(match) ?? rule.cmd;
      if ((rule.guard || cmd == PasswordCommands.generate) && match.start > 0) {
        // Слова перед командой: «Маша просила придумать пароль для wifi»,
        // «напомнить маме сменить пароль» — о другом человеке или деле,
        // это не просьба к навыку.
        final before = text.substring(0, match.start);
        final shownBefore = aligned ? shown.substring(0, match.start) : before;
        if (_foreign(before, shownBefore)) continue;
      }
      final names = match.groupNames;
      if (names.contains('pre')) {
        // Общее правило «… пароль от …»: слова перед паролем.
        final prefix = match.namedGroup('pre') ?? '';
        final shownPrefix = aligned
            ? shown.substring(match.start, match.start + prefix.length)
            : prefix;
        if (_foreign(prefix, shownPrefix)) continue;
      }
      String? raw;
      if (names.contains('rest')) {
        raw = _signInService(match.namedGroup('rest') ?? '');
      } else {
        raw = names.contains('svc')
            ? match.namedGroup('svc')
            : (match.groupCount >= 1 ? match.group(1) : null);
        if (raw != null && aligned) {
          // Название — как написано (регистр).
          final at = match.group(0)!.lastIndexOf(raw);
          if (at >= 0) {
            final start = match.start + at;
            raw = shown.substring(start, start + raw.length);
          }
        }
      }
      final generator = cmd == PasswordCommands.generate;
      final query = generator ? null : _service(raw, utterance);
      final yields = _yields(utterance, text, cmd);
      return PasswordCommand(
        cmd: cmd,
        query: query,
        confidence: yields ? yielded : rule.confidence,
        implicit: yields,
        options: generator ? generatorOptions(text) : const <String, Object?>{},
      );
    }
    if (_single.hasMatch(text)) {
      return const PasswordCommand(
        cmd: PasswordCommands.help,
        confidence: firm,
        implicit: true,
      );
    }
    return null;
  }

  /// Текст для правил: без обращения к помощнику («Лиорио, …», «…,
  /// Лиорио», «…, Лиорио, …» — PersonaAddressing), без вежливых слов по
  /// краям («пожалуйста», «плиз») и с исправленным «пароллей». Обращение
  /// и вежливость не меняют команду, а правила с началом и концом фразы
  /// («запри пароли») без этого их не видят.
  static String _prepare(String text) {
    var value = PersonaAddressing.withoutAddress(text);
    value = value.replaceAll(_doubledL, 'парол');
    value = _clean(value);
    for (var i = 0; i < 2; i++) {
      value = _clean(value.replaceAll(_politeEdge, ''));
    }
    return value;
  }

  /// «Пароллей» — опечатка «паролей» (её уже ловит [_mention]).
  static final RegExp _doubledL = RegExp(r'парол{2,}', caseSensitive: false);

  /// Вежливые слова в начале и в конце фразы.
  static final RegExp _politeEdge = RegExp(
    r'^(?:пожалуйста|плиз|пж)(?:[\s,]+|$)|'
    r'[\s,]+(?:пожалуйста|плиз|пж|pls|please)$',
    caseSensitive: false,
  );

  /// Генератор без слова «пароль»: число символов или классы символов,
  /// «из N слов» — с паролем, классами символов или известным сервисом
  /// («придумай из 5 слов для роутера»). «Придумай из 5 слов для мамы» —
  /// не генератор.
  static bool _elliptic(String text, RegExpMatch match) {
    final target = match.namedGroup('for');
    if (target != null && !_serviceTarget(target)) return false;
    final tail = match.namedGroup('tail')!.trim();
    if (tail.isNotEmpty) {
      if (!_optionTail.hasMatch(tail)) return false;
      for (final other
          in RegExp(r'(?:^|\s)(?:для|от)\s+([^,]+)').allMatches(tail)) {
        final words = other.group(1)!.split(RegExp(r'\s+'));
        if (!words.any(_serviceTarget)) return false;
      }
    }
    if (RegExp(_chars).hasMatch(text)) return true;
    if (RegExp(r'парол|цифр|букв|символ|знак|заглавн|запомн').hasMatch(text)) {
      return true;
    }
    for (final service
        in RegExp(r'(?:для|от)\s+([^\s,.!?]+)').allMatches(text)) {
      if (ServiceAliases.isKnown(service.group(1)!)) return true;
    }
    return false;
  }

  /// Хвост после параметров генератора — ещё параметры, сервис или
  /// вежливость: «, с заглавными», «без цифр», «для роутера».
  static final RegExp _optionTail = RegExp(
    '^(?:,|$_pw(?:\\s|\$)|(?:без|с|со|и|только|для|от|пожалуйста|плиз|пж|'
    'чтобы|легко|можно|английских|русских)(?:\\s|\$))',
  );

  /// «Для роутера», «для рабочего ноутбука», «для wifi»: последнее слово —
  /// известный сервис или устройство. «Для вк пост», «для отчёта» — нет.
  static bool _serviceTarget(String target) {
    final words = target
        .toLowerCase()
        .split(RegExp(r'[\s,?!.;:]+'))
        .where((String w) => w.isNotEmpty)
        .toList();
    if (words.isEmpty) return false;
    final last = words.last;
    return ServiceAliases.isKnown(last) ||
        RegExp('^$_anyDevice\$').hasMatch(last);
  }

  /// «Одинаковых между сбером и почтой»: оба — известные сервисы.
  static bool _twoServices(String text, RegExpMatch match) =>
      ServiceAliases.isKnown(match.namedGroup('a')!) &&
      ServiceAliases.isKnown(match.namedGroup('b')!);

  /// Проверка своих паролей, а не разговор о паролях вообще и не дело:
  /// «статья про одинаковые пароли», «доклад о надёжности паролей»,
  /// «почему простые пароли опасны» — тема, а не просьба; «провести
  /// лекцию про слабые пароли», «надо объяснить …» — дело (инфинитив или
  /// «надо/нужно» в начале, кроме глаголов самой проверки).
  static bool _ownCheck(String text, RegExpMatch match) {
    if (_aboutTopic.hasMatch(text)) return false;
    final lead = _leadVerb.firstMatch(text);
    if (lead == null) return true;
    if (lead.namedGroup('must') != null) return false;
    return _checkVerbs.contains(lead.namedGroup('verb'));
  }

  /// Тема разговора: «про/о/об …пароли», «почему», «зачем», «опасны».
  static final RegExp _aboutTopic = RegExp(
    r'(?:^|\s)(?:про|о|об|обо)\s+(?:\S+\s+){0,2}?(?:парол|надежност)|'
    r'(?:^|\s)(?:почему|зачем)(?:\s|$)|опасн',
  );

  /// Первое слово — «надо/нужно» или инфинитив.
  static final RegExp _leadVerb = RegExp(
    r'^(?:(?<must>надо|нужно)(?:\s|$)|'
    r'(?<verb>[а-яё]+(?:ть|ти|чь))(?:[\s,]|$))',
  );

  /// Инфинитивы самой проверки: «проверить, есть ли слабые пароли»,
  /// «найти одинаковые пароли». «Есть ли слабые пароли» — не инфинитив.
  static const Set<String> _checkVerbs = <String>{
    'есть',
    'проверить',
    'найти',
    'посмотреть',
    'глянуть',
    'показать',
  };

  /// Логин, учётка — всегда о входе. Почта, адрес, имейл, аккаунт — с
  /// глаголом входа («привязана», «для входа») или у известного сервиса и
  /// устройства: «почту от озона», «почту для рабочего ноутбука». «Почта у
  /// Ивана», «почту для связи с поддержкой», «почта в Химках» — не вход.
  static bool _loginTarget(String text, RegExpMatch match) {
    final names = match.groupNames;
    final noun = names.contains('noun') ? match.namedGroup('noun') ?? '' : '';
    if (RegExp(r'^(?:логин|имя пользователя|учетк)').hasMatch(noun)) {
      return true;
    }
    if (names.contains('sign') && match.namedGroup('sign') != null) {
      return true;
    }
    final svc = names.contains('svc') ? match.namedGroup('svc') ?? '' : '';
    final words = svc
        .toLowerCase()
        .split(RegExp(r'[\s,?!.;:]+'))
        .where((String w) => w.isNotEmpty)
        .take(3);
    final device = RegExp('^$_anyDevice\$');
    return words.any(
      (String w) =>
          ServiceAliases.isKnown(w) ||
          device.hasMatch(w) ||
          RegExp(r'^(?:входа|регистрац)').hasMatch(w),
    );
  }

  /// «Нужно восстановить доступ» — просьба; «нужно перенести данные» без
  /// «как» — дело ([_recover]).
  static bool _recoverAsk(String text, RegExpMatch match) =>
      match.namedGroup('lead') == 'как' ||
      match.namedGroup('obj') == 'доступ' ||
      RegExp(r'(?:^|\s)как(?:$|[\s?,])').hasMatch(text);

  /// «На какой почте …» — вопрос о входе, только если это логин или во
  /// фразе есть глагол входа и регистрации: «на какую почту отправить
  /// отчёт» — не о нём.
  static bool _signInRest(String text, RegExpMatch match) {
    final noun = match.namedGroup('noun');
    if (noun != null && noun.startsWith('логин')) return true;
    final rest = match.namedGroup('rest')!;
    // «На какой почте я в озоне был» — о себе; «на какой адрес была
    // доставка» — не о входе.
    return RegExp('(?:^|\\s)$_signIn(?:\\s|\$)').hasMatch(rest) ||
        RegExp(r'(?:^|\s)я\s(?:.*\s)?(?:был|была)(?:\s|$)').hasMatch(rest);
  }

  /// Команда по глаголу в конце: «пароль от вк, скопируй» — копия.
  static String _byTailVerb(RegExpMatch match) =>
      match.namedGroup('verb') == 'скопируй'
          ? PasswordCommands.copy
          : PasswordCommands.reveal;

  /// Сервис из «… я ходил в сбер», «… висит мой аккаунт в сбере»: без
  /// «я», притяжательных, глаголов входа и предлогов.
  static String? _signInService(String rest) {
    final skip = RegExp('^(?:я|мой|моя|мою|свой|свою|там|аккаунт|учетка|'
        'учетку|в|на|к|для|от|у|при|входа|$_signIn)\$');
    final words = rest
        .replaceAll(RegExp(r'[?!.,;:]+.*$'), '')
        .split(RegExp(r'\s+'))
        .where((String w) => w.isNotEmpty && !skip.hasMatch(w))
        .toList();
    return words.isEmpty ? null : words.join(' ');
  }

  /// Параметры генератора из фразы: «на 24 символа», «из 6 слов», «без
  /// символов», «только буквы и цифры», «без похожих», «запоминающийся».
  /// Слова — только английские (EFF): русских режимов нет (решение
  /// владельца №6). Пусто — значения по умолчанию.
  static Map<String, Object?> generatorOptions(String text) {
    final lower = text.toLowerCase();
    final options = <String, Object?>{};
    final words = RegExp(r'из\s+(?:(\d+)\s+)?(?:английских\s+)?слов|'
            r'запоминающ|фраз[аыу]|парольн\S* фраз')
        .firstMatch(lower);
    final chars = RegExp(r'(?:на|из|в|длиной)\s+(\d+)\s+(?:символ|знак|букв)')
        .firstMatch(lower);
    if (words != null && chars == null) {
      options['mode'] = 'words';
      final count = int.tryParse(words.group(1) ?? '');
      if (count != null) options['words'] = count;
    } else {
      options['mode'] = 'characters';
      final length = int.tryParse(chars?.group(1) ?? '');
      if (length != null) options['length'] = length;
    }
    // «без цифр и символов», «без символов, цифр» — каждое слово после
    // одного «без».
    const without = r'без\s+(?:[а-яё]+\s*(?:,\s*|\s+и\s+))*';
    if (RegExp('$without(?:спец\\S*\\s*)?(?:символов|знаков)|'
            r'только\s+(?:из\s+)?букв\S*\s+и\s+цифр|из\s+букв\s+и\s+цифр')
        .hasMatch(lower)) {
      options['symbols'] = false;
    }
    if (RegExp('$withoutцифр').hasMatch(lower)) options['digits'] = false;
    if (RegExp('$withoutпохожих').hasMatch(lower)) {
      options['noLookAlike'] = true;
    }
    return options;
  }

  /// Хоть одно опорное слово: без него фраза точно не о паролях.
  static final RegExp _anchor = RegExp(
    r'парол|пасс|password|логин|почт|имейл|емейл|e-?mail|адрес|аккаунт|'
    r'учетк|имя пользователя|под каким|регистр|регал|зарегил|хранилищ|сейф|'
    r'мастер|главн|доступ|телефон|смартфон|айфон|ноутбук|ноут|планшет|комп|'
    r'мобил|аппарат|устройств|тренир|памят|импорт|бэкап|резервн|копи|'
    r'браузер|хром|сафари|опер|firefox|текстовик|txt|csv|одинаков|записей|'
    r'\d+\s+(?:символ|знак|букв)|из\s+\d+\s+слов',
  );

  static bool _yields(Utterance utterance, String text, String cmd) {
    // «Напомни мне пароль от почты» — просьба подсказать; «напомни
    // сменить пароль» — задача.
    var rest = text.replaceFirst(_remindPassword, '');
    // «Пароль от вк напомни», «почту от озона напомни» — та же просьба с
    // глаголом в конце. «Пароль от вк поменять, напомни» — задача:
    // инфинитив перед глаголом.
    final tail = _remindTail.firstMatch(rest);
    if (tail != null && _remindTailHead.hasMatch(rest)) {
      final head = rest.substring(0, tail.start);
      if (!head.split(RegExp(r'[\s,]+')).any(_infinitive.hasMatch)) {
        rest = head;
      }
    }
    if (_taskMarker.hasMatch(rest)) return true;
    if (utterance.hashtags.isNotEmpty) return true;
    // «пароль на 24 символа» — не срок.
    if (cmd == PasswordCommands.generate) return false;
    return utterance.due.spans.isNotEmpty;
  }

  /// Слова, с которых начинается уже не название: «сменился», «не
  /// работает», получатель «гостям».
  static const Set<String> _stopWords = <String>{
    'сменили',
    'поменяли',
    'изменили',
    'сломали',
    'не',
    'работает',
    'слетел',
    'пропал',
    'новый',
    'старый',
    'нужен',
    'нужно',
    'надо',
  };

  /// Название сервиса обрывается на числе (коды домофона в ответ не
  /// попадают никогда), на возвратном глаголе («сменился») и на
  /// стоп-словах. Первое слово остаётся всегда, кроме числа.
  static String _cutTail(String value) {
    final words = value.split(RegExp(r'\s+'));
    final kept = <String>[];
    for (final word in words) {
      final lower = word.toLowerCase();
      if (RegExp(r'^\d+$').hasMatch(lower)) break;
      if (kept.isNotEmpty &&
          (_stopWords.contains(lower) ||
              _recipients.contains(lower) ||
              RegExp(r'(?:ся|сь)$').hasMatch(lower))) {
        break;
      }
      kept.add(word);
    }
    return kept.join(' ');
  }

  static String _clean(String text) => text
      .replaceAll(RegExp(r'[«»"“”„]'), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .replaceAll(RegExp(r'^[\s,.!?;:—–-]+|[\s,.!?;:—–…]+$'), '')
      .trim();

  /// Сервис: из кавычек, иначе остаток после предлога без хвоста.
  static String? _service(String? raw, Utterance utterance) {
    if (utterance.quotedTitles.isNotEmpty) {
      final quoted = utterance.quotedTitles.first.text.trim();
      if (quoted.isNotEmpty) return ServiceAliases.display(quoted);
    }
    if (raw == null) return null;
    var value = raw.replaceAll(RegExp(r'[?!.,;:]+.*$'), '').trim();
    value = _cutTail(value);
    final tail = _tail.firstMatch(value.toLowerCase());
    if (tail != null) value = value.substring(0, tail.start).trim();
    // «от почты в задачи» и подобное уже ушло задачам; «у меня» — не
    // сервис.
    value = value.replaceAll(_possessive, '');
    // «нужен пароль у меня от почты»: правило «пароль у …» взяло «меня от
    // почты» — сервис после предлога.
    value = value.replaceFirst(_holder, '');
    if (_holderOnly.hasMatch(value)) return null;
    value = value.replaceAll(_possessive, '');
    if (value.isEmpty || value.length > 60) return null;
    return ServiceAliases.display(value);
  }
}

/// Правило разбора: шаблон, команда и уверенность. Именованные группы:
/// `svc` — сервис, `pre` — слова перед паролем (их проверяет
/// [PasswordPhrases._foreign]), `rest` — остаток вопроса о входе, `verb` —
/// глагол, по которому выбирается команда ([cmdOf]). Без них первая
/// группа — сервис.
final class _Rule {
  const _Rule(
    this.pattern,
    this.cmd,
    this.confidence, {
    this.guard = false,
    this.cmdOf,
    this.when,
    this.statement = false,
  });

  final RegExp pattern;
  final String cmd;
  final double confidence;

  /// Слова перед совпадением проверяет [PasswordPhrases._foreign]:
  /// «напомнить маме сменить пароль от почты» — не просьба к навыку.
  final bool guard;

  /// Команда по совпадению вместо [cmd].
  final String Function(RegExpMatch match)? cmdOf;

  /// Дополнительное условие: без него совпадение не считается.
  final bool Function(String text, RegExpMatch match)? when;

  /// Только утверждение или просьба, не вопрос ([Utterance.isQuestion]):
  /// «тренировка памяти, давай?» — разговор о тренировке.
  final bool statement;
}
