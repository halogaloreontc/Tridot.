/// Разобранная фраза: команда, сервис и уверенность. В ней нет и не
/// бывает пароля: значение из чата навык не берёт никогда.
final class PasswordCommand {
  const PasswordCommand({
    required this.cmd,
    required this.confidence,
    this.query,
    this.implicit = false,
    this.options = const <String, Object?>{},
  });

  final String cmd;

  /// Сервис из фразы для ответа («почта», «Т-Банк») или `null`.
  final String? query;

  final double confidence;

  /// Совпадение без уверенности: уступает любому явному (маркеры задачи,
  /// одно слово «пароль»).
  final bool implicit;

  /// Параметры без секретов: у генератора — режим, длина, число слов,
  /// классы символов (`GeneratorOptions.toJson`).
  final Map<String, Object?> options;

  @override
  String toString() => 'PasswordCommand($cmd)';
}

/// Чистый разбор фраз о паролях: без ввода-вывода и без сейфа.
///
/// Его же спрашивает маршрутизатор: распознанную фразу не получает ни
/// один сетевой коннектор, а при выключенном навыке она получает ответ
/// `passwords.off`, а не становится задачей.
abstract final class PasswordPhrases {
  /// Уверенность, начиная с которой фраза — команда навыка
  /// (`passwords.off` при выключенном навыке).
  static const double firm = 0.55;

  /// С маркерами задачи («в задачи», «напомни», срок, `#метка`) фраза
  /// уходит задачам.
  static const double yielded = 0.3;

  static const String _pw =
      r'(?:пароль|пароля|паролю|пароли|паролей|пасс|password)';
  static const String _prep = r'(?:от|для|к|на|у)';
  static const String _forgot =
      r'(?:забыл|забыла|забыли|позабыл|позабыла|не помню|не могу вспомнить|'
      r'не вспомню|помоги\s+(?:мне\s+)?вспомнить)';
  static const String _my = r'(?:(?:мой|свой|мою|свою|мне|у меня)\s+)?';

  /// Один пароль (не «пароли» — это список).
  static const String _onePw = r'(?:пароль|пароля|пасс|password)';

  /// «Напомни (мне)» перед паролем или логином — просьба подсказать, а не
  /// задача-напоминание. «Напомните пожалуйста», «напоминай мне».
  static const String _remind = r'(?:напомни(?:те)?|подскажи(?:те)?|напоминай)'
      r'(?:\s+(?:мне|пожалуйста|пж|плиз))*';

  /// Вежливые слова между глаголом и паролем: «скинь пж пароль от вк».
  static const String _please = r'(?:\s+(?:пожалуйста|пж|плиз|pls))*';

  /// Сейф — имя навыка в интерфейсе: «сейф», «сейф паролей», «хранилище
  /// паролей», «хранилище с паролями». Голое «хранилище» — не сейф
  /// (решение владельца 5): в приложении есть и общие данные, а слово
  /// «Хранилище» оставлено за будущим «Хранилищем контекста». Сейфом оно
  /// становится, только когда во фразе есть слово о паролях — до или после:
  /// «импорт из старого хранилища, мастер-пароль не помню». «Сейфовая
  /// дверь» — не сейф: после «сейф» — только падежное окончание.
  static const String _safe =
      r'(?:сейф(?:а|у|е|ом)?(?![а-яё])(?:\s+(?:паролей|с\s+паролями))?|'
      r'хранилищ[а-яё]*(?:\s+(?:паролей|с\s+паролями)|(?=.*парол)|'
      r'(?<=парол.*)))';

  /// Опора «о паролях» для просмотра вперёд: пароль (и мастер-пароль) или
  /// сейф ([_safe]).
  static const String _pwOrSafe = '(?:парол|$_safe)';

  /// Сейф как предмет «открой» и «запри»: «пароли», «сейф», «хранилище
  /// паролей», «кошелёк с паролями», «доступ к паролям».
  static const String _vault = '(?:мои\\s+|мой\\s+)?(?:пароли|$_safe|'
      r'менеджер\s+паролей|кошелек\s+(?:с\s+паролями|паролей)|'
      'доступ\\s+к\\s+(?:паролям|$_safe))';

  /// Сейф и конец фразы или хвост через запятую или тире («закрой сейф,
  /// уходим»).
  static const String _vaultTail = '$_vault(?=\$|\\s*,|\\s+[—–-]\\s)';

  /// «Логин и пароль», «пароль и логин»: человек забыл оба.
  static const String _loginAndPw =
      '(?:(?:логин|имя пользователя)\\s+и\\s+$_pw|$_pw\\s+и\\s+логин)';

  /// Голые устройства (без слова о паролях) — только целой фразой:
  /// «купить чехол, потерял телефон» — задача, а не навык.
  static const String _device =
      r'(?:телефон|смартфон|ноутбук|ноут|планшет|компьютер)';

  /// «(новый, надёжный …) пароль» после глагола генератора.
  static const String _newPw =
      '(?:новый\\s+|надежный\\s+|сложный\\s+|случайный\\s+|хороший\\s+|'
      'длинный\\s+|запоминающийся\\s+|простой\\s+|стойкий\\s+)*$_pw';

  /// Устройство (без слова о паролях — только вместе с потерей или
  /// переездом): «телефон», «ноут», «мобила», «аппарат», «комп».
  static const String _anyDevice =
      r'(?:телефон|смартфон|айфон|ноутбук|ноут|компьютер|комп|планшет|мобил|'
      r'аппарат|устройств)[а-яё]*';

  /// Потеря или поломка устройства в любом порядке слов: «потерял
  /// телефон», «телефон украли», «мобила сломалась», «разбил экран на
  /// телефоне». Между глаголом и устройством — не «пароль»: «потерял
  /// пароль от телефона» — о пароле, а не о телефоне.
  static const String _deviceLoss =
      '(?:потерял|потерян|украл|украден|разбил|разбит|сломал|утопил|посеял)'
      '[а-яё]*\\s+(?:(?!парол)\\S+\\s+){0,2}?$_anyDevice|'
      '$_anyDevice\\s+(?:(?!парол)\\S+\\s+)?(?:(?:потерял|потерян|украл|'
      'украден|разбил|разбит|сломал|сломает|утопил|пропал)[а-яё]*|'
      'не\\s+включается|не\\s+работает)';

  /// Переезд на другое устройство: «переезжаю на рабочий ноутбук», «при
