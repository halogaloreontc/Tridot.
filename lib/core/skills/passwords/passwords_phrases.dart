  /// новый ноутбук», «из старого ноута в новый». «Сменил пароль телефона» —
  /// не переезд: слово между глаголом и устройством — не «пароль».
  static const String _deviceMove =
      '(?:переезд|переезжа|перееха|перехож)[а-яё]*\\s+(?:на\\s+)?(?:\\S+\\s+)?'
      '$_anyDevice|'
      '(?:покупк|купил|сменил|поменял)[а-яё]*\\s+(?:(?!парол)\\S+\\s+)?'
      '$_anyDevice|'
      '$_anyDevice\\s+(?:купил|сменил|поменял)[а-яё]*|'
      '(?:перенести|переносить|переставить|перекинуть|вытащить|достать|'
      'забрать|перенос)\\s+(?:\\S+\\s+){0,3}?(?:на|в)\\s+(?:\\S+\\s+)?'
      '$_anyDevice|'
      'из\\s+стар[а-яё]*\\s+$_anyDevice';

  /// Вопрос, как вернуть данные: «как восстановить всё», «как вернуть
  /// доступ к данным», «нужно восстановить доступ», «как перенести всё
  /// туда», «перенести всё из старого ноута в новый». После предмета —
  /// конец фразы, «туда», устройство («на новый», «из старого ноута») или
  /// «к данным, аккаунтам»: «нужно вернуть всё в магазин», «восстановить
  /// базу в 1С», «перенести все контакты» — не о сейфе. «Нужно, надо»
  /// без «как» — только с доступом ([_recoverAsk]): «купил ноутбук, нужно
  /// перенести данные» — дело.
  static const String _recover =
      '(?<lead>как|нужно|надо)\\s+(?:мне\\s+)?(?:теперь\\s+)?(?:восстановить|'
      'вернуть|перенести|достать|вытащить)\\s+(?<obj>всё|все|доступ|данные|базу)'
      '(?:\\s+(?:туда|сюда|обратно|'
      '(?:на|в|из)\\s+(?:\\S+\\s+)?(?:$_anyDevice|нов[а-яё]*|друг[а-яё]*|него|нее)'
      '(?:\\s+(?:на|в)\\s+(?:нов|друг)[а-яё]*)?|'
      'к\\s+(?:моим\\s+|своим\\s+)?(?:данн|аккаунт|парол|хранилищ|сервис|учетк|'
      'почт|приложени)[а-яё]*))?(?:\\s*[,?!.].*)?\$';

  /// Качество нового пароля: генератор, а не забытый пароль.
  static const String _quality =
      r'(?:надежн|сложн|случайн|длинн|запоминающ|прост|стойк|хорош|'
      r'безопасн|крепк)[а-яё]*';

  /// Параметры генератора: «на 20 символов», «из 10 букв», «из 5 слов».
  static const String _chars =
      r'(?:на|из|длиной|в)\s+\d+\s+(?:символ|знак|букв)[а-яё]*';
  static const String _wordsParam = r'из\s+\d+\s+(?:английских\s+)?слов';

  /// Браузеры — источники импорта (только у навыка «Пароли»). «Яндекс» —
  /// ещё и сервис, поэтому один он браузером не считается.
  static const String _browser =
      r'(?:браузер[а-яё]*|хром(?:а|е|ом)?|chrome|опер[аыуе]|opera|сафари|'
      r'safari|firefox|файрфокс[а-яё]*|фаерфокс[а-яё]*|мозилл?[аыу]|edge|'
      r'эдж[а-яё]*|яндекс[\s.]?браузер[а-яё]*)(?=$|[\s?,.!])';

  /// Браузеры без «оперы» по-русски: «из оперы» — ещё и театр.
  static const String _browserStrict =
      r'(?:браузер[а-яё]*|хром(?:а|е|ом)?|chrome|opera|сафари|'
      r'safari|firefox|файрфокс[а-яё]*|фаерфокс[а-яё]*|мозилл?[аыу]|edge|'
      r'эдж[а-яё]*|яндекс[\s.]?браузер[а-яё]*)(?=$|[\s?,.!])';

  /// Служебные слова между копией или импортом и тем, что копируют: «импорт
  /// из старого хранилища», «копию всех паролей», «из двух браузеров».
  static const String _link =
      r'(?:из|с|со|от|для|в|во|на|моих|моего|моей|всех|всего|старого|'
      r'старых|своих|своего|нового|этого|двух|разных|нескольких|других|'
      r'другого)';

  /// Предмет импорта без слова «пароли»: «всё», «данные», «список».
  static const String _importObject =
      r'(?:(?:мои|всё|все|данные|список|записи)\s+)?';

  /// Файл для импорта: «из текстовика», «из csv».
  static const String _importFile =
      r'(?:текстовик[а-яё]*|txt|csv)(?=$|[\s?,.!])';

  /// Вопрос о том, как работает импорт или копия: справка, а не команда.
  static const String _howQuestion =
      r'как\s+(?:это\s+)?(?:\S+\s+)?(?:работает|сделать|делать)|'
      // «Можно импортировать пароли из файла?» — вежливая просьба, не
      // вопрос: после «можно» глагол с паролями.
      r'можно\s+(?:ли\s+)?(?!\S+\s+(?:мои\s+|все\s+)?пароли(?:\s|$))|'
      r'возмож[а-яё]*|есть\s+или|что\s+делать|'
      r'не\s+(?:всё|все)\s+\S+|не\s+открывается|не\s+работает|'
      r'в\s+ч[её]м\s+(?:может\s+быть\s+)?дело|поврежд[а-яё]*|повредил[а-яё]*';

  /// Логин, почта для входа, аккаунт.
  static const String _loginNoun =
      r'(?:логин|имя пользователя|адрес\s+почты|почтовый\s+адрес|почта|'
      r'аккаунт|учетк[аиу]|e-?mail|имейл|емейл)';

  /// Вход и регистрация: «регистрировался», «регался», «зарегил»,
  /// «приписан», «висит», «сижу», «вбивал», «для входа». «Был, была» —
  /// не вход: «на какой адрес была доставка».
  static const String _signIn =
      r'(?:(?:регистрир|зарегистр|регал|зарегал|зарегил|регил|заходил|'
      r'входил|ставил|создан|привязан|приписан|указан|использовал|вбивал)'
      r'[а-яё]*|ходил|захожу|вхожу|зашел|зашла|сижу|вишу|висю|висит|'
      r'для\s+входа)';

  /// Отглагольное действие над паролем перед ним — название дела, а не
  /// просьба к навыку: «смена пароля от госуслуг в середине марта».
  static const Set<String> _actionNouns = <String>{
    'смена',
    'смену',
    'замена',
    'замену',
    'сброс',
    'установка',
    'установку',
    'обновление',
  };

  static final List<_Rule> _rules = <_Rule>[
    // «забыл мастер-пароль», «не помню пароль от сейфа».
    _Rule(
      RegExp('$_forgot\\s+$_my(?:мастер[- ]?пароль|главный пароль)'),
