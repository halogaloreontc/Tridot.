      0.9,
    ),
    // «Тренировка памяти» без слова о паролях — команда, только когда это
    // вся фраза (как «потренируй мою память», pw-133) или после неё —
    // слово-просьба: «тренировка памяти посложнее, я уже простые
    // запоминаю», «режим тренировки памяти, давай». Остальное — разговор
