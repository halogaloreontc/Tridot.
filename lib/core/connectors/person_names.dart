  static final Set<String> _plain = <String>{
    for (final name in <String>[..._male, ..._female]) ..._forms(name),
  };

  static final Set<String> _contextual = <String>{
    for (final name in _ambiguous) ..._forms(name),
    // «Павел» склоняется с беглой гласной: «Павла», «Павлу».
    'павел', 'павла', 'павлу', 'павлом', 'павле',
  };

  /// Именительный и косвенные падежи имени [name].
  static Set<String> _forms(String name) {
    final base = name.replaceAll('ё', 'е');
    final result = <String>{base};
    final last = base[base.length - 1];
    final stem = base.substring(0, base.length - 1);
    if (base == 'любовь') {
      return result..addAll(<String>['любви', 'любовью']);
    }
    if (base.endsWith('ия')) {
      // «Мария»: Марии, Марию, Марией.
      result.addAll(<String>['$stemи', '$stemю', '$stemей']);
    } else if (last == 'а' || last == 'я') {
      final soft = last == 'я';
      final hush = 'гкхжшчщ'.contains(stem[stem.length - 1]);
      final sibilant = 'жшчщц'.contains(stem[stem.length - 1]);
      result.addAll(<String>[
        hush || soft ? '$stemи' : '$stemы',
        '$stemе',
        soft ? '$stemю' : '$stemу',
        soft || sibilant ? '$stemей' : '$stemой',
      ]);
    } else if (last == 'й' || last == 'ь') {
      // «Андрей», «Игорь»: Андрея, Андрею, Андреем, Андрее.
      result.addAll(<String>[
        '$stemя',
        '$stemю',
        '$stemем',
        '$stemе',
        if (base.endsWith('ий')) '$stemи',
      ]);
    } else {
      // «Иван», «Олег»: Ивана, Ивану, Иваном, Иване.
      result.addAll(<String>[
        '$baseа',
        '$baseу',
        'шжчщц'.contains(last) ? '$baseем' : '$baseом',
        '$baseе',
      ]);
    }
    return result;
  }

  /// Падежи имён, которые чаще — обычные слова: «позвонить жене» — жена,
  /// а не Женя. Со строчной такое слово остаётся со строчной.
  static const Set<String> _commonForms = <String>{'жене', 'сене'};

  /// Похоже ли слово [word] (нижний регистр) на имя, если перед ним
  /// [previous].
  static bool isName(String word, {String? previous}) {
    final normalized = word.toLowerCase().replaceAll('ё', 'е');
    if (_commonForms.contains(normalized)) return false;
    if (_plain.contains(normalized)) return true;
    return previous != null &&
        _contextual.contains(normalized) &&
        _personContext.contains(previous.toLowerCase().replaceAll('ё', 'е'));
  }

  static final RegExp _word = RegExp(r'[А-Яа-яЁё]+');

  /// [title] с именами людей с заглавной: «Написать андрею» → «Написать
  /// Андрею». Остальные слова не меняются.
  static String capitalizeIn(String title) {
    String? previous;
    return title.replaceAllMapped(_word, (Match match) {
      final word = match.group(0)!;
      final before = previous;
      previous = word;
      if (word[0] != word[0].toLowerCase()) return word;
      if (!isName(word, previous: before)) return word;
      return '${word[0].toUpperCase()}${word.substring(1)}';
    });
  }
