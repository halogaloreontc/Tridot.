  /// Порядковое число месяца с [i]-го слова, в том числе составное
  /// («двадцать пятого», «тридцать первое»): (число, окончание, номер
  /// последнего слова).
  static (int, String, int)? dayOrdinalAt(
    List<String> words,
    int i, {
    bool Function(int left, int right)? adjacent,
  }) {
    final single = ordinal(words[i]);
    if (single != null) return (single.$1, single.$2, i);
    final tens = switch (words[i]) {
      'двадцать' => 20,
      'тридцать' => 30,
      _ => null,
    };
    if (tens == null || i + 1 >= words.length) return null;
    if (adjacent != null && !adjacent(i, i + 1)) return null;
    final unit = ordinal(words[i + 1]);
    if (unit == null || unit.$1 > 9 || (tens == 30 && unit.$1 > 1)) {
      return null;
    }
    return (tens + unit.$1, unit.$2, i + 1);
  }
}

/// Число словами в тексте: [start]–[end] — его слова, [value] — значение.
final class NumberWordMatch {
  const NumberWordMatch(this.start, this.end, this.value);

  final int start;
  final int end;
  final int value;
}
