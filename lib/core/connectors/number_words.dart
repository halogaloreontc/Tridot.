  /// Значение одного слова: «семь» → 7, «восьмисот» → 800.
  static int? value(String word) => ranked[word]?.$1;

  /// Количественные числа словами в [text], составные целиком: «сто сорок
  /// четыре» → 144, «тыща две» → 1002, «две тысячи» → 2000. Ранги внутри
  /// числа убывают: «восемь тридцать» — два числа (8 и 30), как время на
  /// часах. Числа до 9999.
  static List<NumberWordMatch> find(String text) {
    final words = _word.allMatches(text).toList(growable: false);
    bool adjacent(int left, int right) =>
        text.substring(words[left].end, words[right].start).trim().isEmpty;
    final result = <NumberWordMatch>[];
    for (var i = 0; i < words.length; i++) {
      final read = _read(words, i, adjacent);
      if (read == null) continue;
      final (number, last) = read;
      result.add(NumberWordMatch(words[i].start, words[last].end, number));
      i = last;
    }
    return result;
  }

  /// Число с [i]-го слова: (значение, номер последнего слова).
  static (int, int)? _read(
    List<RegExpMatch> words,
    int i,
    bool Function(int, int) adjacent,
  ) {
    String at(int k) => words[k].group(0)!;
    var thousandsPart = 0;
    var total = 0;
    var rank = 3;
    var last = -1;
    // Падеж первого слова: «двадцати шесть» («без двадцати шесть») — два
    // числа, «двадцать шесть» и «двадцати шести» — одно.
    bool? oblique;
    var k = i;
    while (k < words.length) {
      if (k > i && !adjacent(k - 1, k)) break;
      final word = at(k);
      if (thousands.contains(word)) {
        if (thousandsPart != 0 || rank == -1) break;
        thousandsPart = (total == 0 ? 1 : total) * 1000;
        total = 0;
        rank = 3;
        last = k;
        k++;
        continue;
      }
      final entry = ranked[word];
      if (entry == null) break;
      final (number, wordRank) = entry;
      // Ноль — только сам по себе: «ноль пять» — два числа.
      if (wordRank == -1) {
        if (last != -1) break;
        last = k;
        rank = -1;
        k++;
        break;
      }
      if (wordRank >= rank) break;
      final wordOblique = !_nominative.contains(word);
      if (oblique != null && oblique != wordOblique) break;
      oblique = wordOblique;
      // После десятков — только единицы 1–9: «двадцать пять», но
      // «двадцать пятнадцать» — два числа.
      if (rank == 1 && number >= 10) break;
      total += number;
      rank = wordRank;
      last = k;
      k++;
    }
    if (last == -1) return null;
    return (thousandsPart + total, last);
  }

  /// Порядковое число 1–31 одним словом и его окончание, сведённое к
  /// окончанию после цифр: «первому» → (1, «ому»), «пятого» → (5,
  /// «ого»), «двадцатое» → (20, «ое»), «третьему» → (3, «ому»).
  static (int, String)? ordinal(String word) {
    for (final (ending, same) in _ordinalEndings) {
      if (!word.endsWith(ending)) continue;
      final day = _ordinalStems[word.substring(0, word.length - ending.length)];
      if (day == null) continue;
      return (day, same);
    }
    return null;
  }

  /// Окончания порядкового словом и такие же окончания после цифр.
  static const List<(String, String)> _ordinalEndings = <(String, String)>[
    ('ому', 'ому'),
    ('ого', 'ого'),
    ('ое', 'ое'),
    ('ьему', 'ому'),
    ('ьего', 'ого'),
    ('ье', 'ое'),
  ];

  static const Map<String, int> _ordinalStems = <String, int>{
