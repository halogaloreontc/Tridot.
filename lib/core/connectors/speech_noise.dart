/// Слова-шум устной речи: обрывки, которые распознаватель голоса пишет
/// вместо пауз и междометий, и разговорные вставки перед просьбой.
///
/// Один список на всех: его читают и нормализация распознанного текста
/// (`VoiceText`), и разбор команд ([ScenarioParser]), поэтому набранное
/// вручную «эм, напомни …» понимается так же, как надиктованное. Слова —
/// нормализованные: нижний регистр, «е» вместо «ё».
abstract final class SpeechNoise {
  /// Обрывки распознавателя и междометия: «поставь зэд напоминание»,
  /// «ээ напомни». Значения у них нет, поэтому они убираются из любого
  /// места фразы вне кавычек. Одиночное «э» сюда не входит: это и буква
  /// («витамин э»), его убирает только [isLeadFiller] в начале фразы.
  static const Set<String> junk = <String>{
    'зэд',
    'зед',
    'ээ',
    'эээ',
    'эмм',
    'эммм',
    'ммм',
    'хм',
    'хмм',
    'кхм',
  };

  /// Междометия, которые бывают и словами: «сверло 6 мм», «размер эм»,
  /// «буква зет». Шум они только в начале фразы: «мм, напомни …».
  static const Set<String> leadJunk = <String>{
    'мм',
    'эм',
    'зет',
    'зэт',
    'гм',
  };

  /// Разговорные вставки перед просьбой: «нужен напомни …», «ну это
  /// напомни …», «короче, поставь …». Убираются только до слова команды:
  /// в названии они могут быть по делу («вот это купить»).
  static const Set<String> leadFillers = <String>{
    'нужен',
    'нужна',
    'нужны',
    'э',
    'это',
    'вот',
    'короче',
    'типа',
    'значит',
    'слушай-ка',
    'смотри',
    'кстати',
    // Обращение к другому помощнику по привычке: «ок гугл, напомни …».
    'ок',
    'окей',
    'гугл',
    'алиса',
  };

  static bool isJunk(String word) => junk.contains(word);

  /// Шум в начале фразы: [junk] и [leadJunk].
  static bool isLeadNoise(String word) =>
      junk.contains(word) || leadJunk.contains(word);

  static bool isLeadFiller(String word) =>
      isLeadNoise(word) || leadFillers.contains(word);
}
