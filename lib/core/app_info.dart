/// Название приложения для пользователя (ADR-009).
///
/// Приложение — хаб, в котором работают помощники Liorio и Noda; само оно
/// помощником не называется, а помощники не называют себя «связными».
///
/// Только название: id пакета, bundle id и папка данных остались прежними
/// (ADR-008, ADR-009).
abstract final class AppInfo {
  /// Название в русском интерфейсе: боковая панель, заголовок окна,
  /// «О приложении», автор встроенных расширений.
  static const String name = 'Связной';

  /// Латинское название — там, где нужно имя латиницей или текст
  /// английский: `Relay.app` на macOS, свойства файла в Windows.
  static const String latinName = 'Relay';

  /// «Связной» — субстантивированное прилагательное и склоняется как
  /// прилагательное: «Связного», «в Связном». Формы — здесь, чтобы текст
  /// с названием в косвенном падеже не собирал их сам.
  static const String nameGenitive = 'Связного';

  /// Дательный падеж: «Связному».
  static const String nameDative = 'Связному';

  /// Творительный падеж: «Связным».
  static const String nameInstrumental = 'Связным';

  /// Предложный падеж: «(в) Связном».
  static const String namePrepositional = 'Связном';

  /// Раздел приложения с помощниками, сводкой и настройками: «Мой
  /// Связной». Одна константа, чтобы смена названия была правкой в одном
  /// месте.
  static const String hubName = 'Мой $name';

  /// Версия для пользователя — как `version:` в pubspec.yaml до «+»
  /// (тест держит их вместе). Видна в меню рядом с названием.
  static const String version = '0.1.0';

  /// Номер сборки — число после «+» в pubspec.yaml.
  static const int build = 1;
}
