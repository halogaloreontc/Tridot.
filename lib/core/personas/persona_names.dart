/// Проверка имени помощника при переименовании (ADR-016).
///
/// Имя — обращение: «Мира, добавь задачу». Поэтому оно не может совпадать
/// с именем другого помощника и с обращением к подключению («склад, …»,
/// «пароли, …»): иначе фраза ушла бы не туда.
abstract final class PersonaNames {
  /// Самое длинное имя, в знаках.
  static const int maxLength = 24;

  /// Самое короткое имя, в знаках: однобуквенное имя («Я», «И», «А») —
  /// начало обычной фразы.
  static const int minLength = 2;

  /// Слова, которыми обращаются к навыкам и подключениям, сверх
  /// подключений ([ConnectionSlots]), навыка «Данные» и названий сервисов
  /// навыка «Пароли».
  static const Set<String> _reserved = <String>{
    'склад',
    'пароли',
    'сейф',
    'задачи',
    'калькулятор',
  };

  /// Слова, с которых начинаются обычные фразы: команды задач и беседы,
  /// приветствие и благодарность, ответы «да» и «нет», местоимения и
  /// союзы. Имя — обращение, а обращение после пробела отрезается от
  /// фразы: помощник «Добавь» забрал бы «добавь задачу хлеб» себе.
  static const Set<String> _phraseWords = <String>{
    // Команды задач и навыков.
    'добавь', 'добавьте', 'добавить', 'создай', 'создайте', 'создать',
    'запиши', 'запишите', 'записать', 'поставь', 'поставьте',
    'напомни', 'напомните', 'напомнить', 'покажи', 'покажите', 'показать',
    'удали', 'удалите', 'удалить', 'перенеси', 'перенесите', 'перенести',
    'отмени', 'отмените', 'отменить', 'отмена', 'отметь', 'отметьте',
    'закрой', 'закройте', 'выполни', 'выполнено', 'готово', 'сделай',
    'сделайте', 'сделано', 'измени', 'переименуй', 'найди', 'найдите',
    'открой', 'посчитай', 'посчитайте', 'сосчитай', 'вычисли', 'сколько',
    'включи', 'включите', 'выключи', 'выключите', 'отключи', 'подключи',
    'скажи', 'скажите', 'расскажи', 'расскажите', 'пошути', 'объясни',
    'помоги', 'помогите', 'пусть', 'говори', 'говорите', 'давай', 'давайте',
    'купи', 'купить', 'позвони', 'позвонить', 'запомни', 'проверь',
    'задача', 'задачу', 'задач', 'дела', 'список', 'план', 'планы',
    'сегодня', 'завтра', 'послезавтра', 'вчера',
    // Приветствие, благодарность, отклики, ответы.
    'привет', 'приветик', 'здравствуй', 'здравствуйте', 'здрасте', 'хай',
    'салют', 'пока', 'спасибо', 'спс', 'благодарю', 'да', 'нет', 'ага',
    'угу', 'неа', 'ок', 'окей', 'конечно', 'хорошо', 'ладно', 'отлично',
    'супер', 'понял', 'поняла', 'ясно', 'стоп', 'хватит', 'еще', 'пожалуйста',
    'слушай', 'слушайте', 'эй', 'ну', 'вот', 'так', 'тогда', 'надо',
    'нужно', 'можешь', 'можете',
    // Вопросы, местоимения, союзы.
    'что', 'как', 'кто', 'где', 'когда', 'почему', 'зачем', 'какой',
    'какая', 'какие', 'чем', 'это', 'все', 'мне', 'нам', 'меня', 'тебя',
    'ты', 'вы', 'мы', 'он', 'она', 'оно', 'они', 'мой', 'моя', 'не', 'ни',
    'но', 'или', 'если', 'бы',
  };

  static final RegExp _letters = RegExp(r'^\p{L}+(?:-\p{L}+)*$', unicode: true);

  /// Обращения к подключениям в нижнем регистре, с «е» вместо «ё».
  static Set<String> get connectorWords => <String>{
        for (final word in <String>{
          ..._reserved,
          for (final slot in ConnectionSlots.all) ...<String>[
            slot.title,
            for (final alias in slot.aliases) alias,
          ],
          ...DataConnector.answerWords,
        })
          Persona.fold(word),
      };

  /// Текст ошибки для имени [name] помощника [id] при составе [cast] или
  /// `null`, если имя годится. Сравнение без учёта регистра и «ё».
  static String? validate(String name, String id, PersonaCast cast) {
    final value = name.trim();
    if (value.isEmpty) return 'Имя не может быть пустым.';
    if (value.length > maxLength) {
      return 'Имя длиннее $maxLength знаков — так неудобно обращаться.';
    }
    if (value.length < minLength) {
      return 'Имя короче $minLength букв — его не отличить от начала фразы.';
    }
    final lower = Persona.fold(value);
    // Обращение к подключению — раньше проверки знаков: «на складе» —
    // тоже обращение, хоть и из двух слов.
    if (connectorWords.contains(lower) || ServiceAliases.isKnown(value)) {
      return 'Имя «$value» занято обращением к подключению — фраза '
          '«$lower, …» ушла бы не туда.';
    }
    if (!_letters.hasMatch(value)) {
      return 'Имя — одно слово: только буквы и дефис, без пробелов.';
    }
    for (final other in cast.members) {
      if (other.id == id) continue;
      if (other.nameForms.contains(lower)) {
        return 'Имя «$value» уже у помощника ${other.russianName} — фраза '
            '«$lower, …» ушла бы не тому.';
      }
    }
    if (_phraseWords.contains(lower) || _isAnswer(value)) {
      return 'Имя «$value» — обычное слово в начале фраз: «$lower …» '
          'ушло бы помощнику, а не в команду.';
    }
    return null;
  }

  /// «Да», «нет», «ок», «отмена» и другие ответы на вопрос подтверждения.
  static bool _isAnswer(String value) {
    final utterance = Utterance.analyze(value, now: DateTime(2000));
    return ConfirmationReply.of(utterance) != null ||
        ConfirmationReply.leading(utterance) != null;
  }
}
