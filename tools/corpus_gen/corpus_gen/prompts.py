"""Промпты и JSON-схемы генерации и разметки.

Разметчик описывает, как фразу ДОЛЖЕН понять помощник, а не как её понимает
текущий парсер. Расхождение с парсером — это и есть найденный пробел.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from .topics import DEFAULT_CONNECTOR, ConnectorTopics, Topic

# Намерения и темы каждого коннектора описаны в topics/*.toml (corpus_gen/topics.py).
ISSUES = ["none", "inPast", "invalidDate", "invalidTime", "conflictingDays", "conflictingTimes", "ambiguousHour"]
TITLE_ISSUES = ["none", "unbalancedQuotes", "multipleTitles"]
PRECISIONS = ["date", "dateTime"]

WEEKDAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]

GENERATION_SYSTEM = """Ты помогаешь тестировать офлайн-помощника на русском языке.
Помощник работает на правилах, без языковой модели. Ты придумываешь реалистичные фразы, которые
живой пользователь мог бы написать в чат помощника. Фразы должны быть разнообразными по лексике,
порядку слов и стилю. Не повторяй примеры дословно. Не используй реальные персональные данные."""

# Правила генерации для коннектора задач (tasks). У других коннекторов — generation_rules
# из их файла тем.
TASKS_GENERATION_RULES = """Пиши фразы так, как пишут в обычный чат: БОЛЬШИНСТВО фраз — без кавычек,
название задачи просто идёт словами рядом с командой и сроком («добавь позвонить маме завтра в 10»,
«напомни мне в пятницу купить хлеб», «запиши сдать отчёт #работа»). Кавычки («…», “…”, „…“ или "…")
используй лишь иногда — примерно в каждой пятой фразе, когда название нужно передать точно."""

GENERATION_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {"phrases": {"type": "array", "items": {"type": "string"}}},
    "required": ["phrases"],
    "additionalProperties": False,
}


def generation_prompt(
    connector: ConnectorTopics,
    topic: Topic,
    count: int,
    examples: list[str],
) -> str:
    sample = "\n".join(f"- {e}" for e in examples[:8]) or "- (примеров нет)"
    rules = connector.generation_rules or (
        TASKS_GENERATION_RULES if connector.id == DEFAULT_CONNECTOR else ""
    )
    area = f"Раздел помощника: {connector.title}"
    if connector.description:
        area += f" — {connector.description}"
    return (
        f"Придумай {count} разных фраз пользователя. {area}. Тема: {topic.description}.\n\n"
        + (f"{rules}\n" if rules else "")
        + "Часть фраз может нарушать правила — это тоже полезно для тестов.\n\n"
        f"Фразы, которые уже есть (не повторяй их):\n{sample}\n\n"
        'Верни JSON: {"phrases": ["…", "…"]}.'
    )


LABEL_SYSTEM = """Ты размечаешь фразы для регрессионных тестов помощника задач. Укажи, как фразу
ДОЛЖЕН понять правильно работающий помощник по спецификации ниже — даже если формулировка редкая.

Намерение (intent):
- createTask — просьба создать задачу или напоминание (добавь, создай, запиши, напомни, новая задача).
- rescheduleTask — перенести срок задачи (перенеси, сдвинь, отложи, передвинь).
- completeTask — команда или сообщение, что задача сделана (заверши, выполнил, готово, сделано).
  Вопросы о статусе («что выполнить?», «я не сделал?») и отрицание самой команды («не выполнил
  отчёт», «не готово») — НЕ completeTask, а unknown. «Не» внутри названия задачи после команды
  не мешает: «Заверши не забыть купить хлеб» — completeTask, title «Не забыть купить хлеб».
- listTasks — показать задачи или планы.
- unknown — всё остальное.
Решает первое по порядку слово-команда вне кавычек: «Добавь задачу выполнить отчёт» — createTask.

Название (title). Кавычки НЕ обязательны: пользователь пишет как в обычном чате.
- Есть парные кавычки « », “ ”, „ “, " " — title = текст внутри кавычек как есть. Слова и даты
  внутри кавычек не влияют на намерение и срок.
- Кавычек нет — title = остаток фразы после удаления (целыми словами, не частями слов):
  * команды и слова-объекта сразу после неё: «добавь задачу», «создай напоминание», «запиши
    дело», «новая задача», «добавь в список», «напомни мне/нам»; «что»/«чтобы» сразу после
    «напомни»;
  * сроков вместе с предлогом перед ними (в, во, на, к, ко, до, с, со, от, через, по, «к концу»):
    «завтра в 10», «на 15.11», «в пятницу», «к 18:00», «через 3 дня»;
  * #хештегов;
  * вежливых слов (пожалуйста, плиз, пж) и лишних знаков препинания по краям.
  Первая буква — заглавная, остальное — как написал пользователь (регистр, «ё», опечатки).
  Слово, только похожее на срок, остаётся в названии: «Добавь задачу купить завтрак» — «Купить
  завтрак»; номера версий, телефонов и артикулов — не сроки: «добавь обновить до версии 2.10» —
  «Обновить до версии 2.10».
  Примеры: «Добавь задачу позвонить клиенту завтра в 10» — «Позвонить клиенту»; «напомни мне
  завтра в 9:30 оплатить интернет» — «Оплатить интернет»; «запиши сдать отчёт #работа» —
  «Сдать отчёт»; «Добавь «Купить хлеб» завтра» — «Купить хлеб».
  Если после удаления ничего не осталось («добавь задачу», «напомни завтра») — title = null.
- Для rescheduleTask и completeTask title — слова, по которым помощник найдёт задачу, к которой
  относится команда (может быть частью названия), после удаления команды, сроков с предлогами и
  служебных слов («задачу», «как выполненную», «выполненной», «готово»): «перенеси звонок
  клиенту на пятницу» — «Звонок клиенту»; «отметь отчёт выполненным» — «Отчёт». Если фраза
  указывает только на контекст («её», «эту задачу», «перенеси на завтра», «готово») — null.
- Для listTasks и unknown — всегда null.
- Незакрытая кавычка: titleIssue = unbalancedQuotes, title = null.
- Несколько названий в кавычках: titleIssue = multipleTitles, title = null.

Срок (due) — только для createTask и rescheduleTask, иначе null:
- Формат «YYYY-MM-DD» без времени (precision = date) или «YYYY-MM-DDTHH:MM» (precision = dateTime).
- «сегодня», «завтра», «послезавтра», дни недели, «через N часов», «15 ноября» и т. п. —
  считай от текущего момента, указанного в запросе.
- Дата ДД.ММ без года — ближайшая не раньше сегодняшнего дня. ДД.ММ.ГГ — год 20ГГ.
- Только время без дня: если оно уже прошло сегодня — завтра в это время.
- Явный день (или дата) и время, которые уже прошли: due = null, issue = inPast.
  Явная дата в прошлом без времени — тоже inPast.
- «с 15:00 на 17:00» — срок 17:00 (берётся значение после «на»).
- Несуществующая дата (31.02): invalidDate. Несуществующее время (24:00, 25:10, «в 7.5»): invalidTime.
- Несколько разных дней: conflictingDays; несколько разных времён: conflictingTimes. В этих
  случаях due = null. Один и тот же день двумя способами («сегодня, 02.11») — не конфликт.
- Час от 1 до 6 без минут и без уточнения «утра/дня/вечера/ночи» («к 5», «в 3») может быть и
  утром, и вечером: due = null, issue = ambiguousHour. «в 5 утра», «в 17», «в 5:00» — понятны.
- «в 2 часа дня» — 14:00, «в 7 часов вечера» — 19:00; эти слова — часть срока, не названия.
- Номера версий («версия 2.10», «flutter до 3.24»), количества («1.5 кг», «3.5 метра»),
  номера служб («позвонить в 03»), телефонов и артикулов (5–6 цифр, «64115») — не сроки.
- Если срока нет: due = null, precision = null, issue = none.

confident = false, если фраза двусмысленна даже для человека; поясни в comment."""

# Общая часть разметки для коннекторов, кроме tasks: их правила — label_rules из файла тем.
CONNECTOR_LABEL_HEADER = """Ты размечаешь фразы для регрессионных тестов офлайн-помощника на русском языке.
Укажи, как фразу ДОЛЖЕН понять правильно работающий помощник по спецификации ниже — даже если
формулировка редкая. Раздел помощника: {title} (коннектор «{id}»).
Допустимые намерения (intent): {intents}. Фразы не про этот раздел — unknown.
Поля title, due и precision всегда null, issue и titleIssue — всегда «none»: корпус проверяет у
этого раздела только маршрутизацию и intent (commandId).
confident = false, если фраза двусмысленна даже для человека; поясни в comment.

Спецификация раздела:
{rules}"""


def label_system(connector: ConnectorTopics) -> str:
    """Системный промпт разметки для фраз коннектора."""
    if connector.id == DEFAULT_CONNECTOR and not connector.label_rules:
        return LABEL_SYSTEM
    return CONNECTOR_LABEL_HEADER.format(
        title=connector.title,
        id=connector.id,
        intents=", ".join(connector.intents),
        rules=connector.label_rules,
    )


_NULLABLE_STRING = {"anyOf": [{"type": "string"}, {"type": "null"}]}


def label_schema(connector: ConnectorTopics) -> dict[str, Any]:
    return {
        "type": "object",
        "properties": {
            "intent": {"type": "string", "enum": list(connector.intents)},
            "title": _NULLABLE_STRING,
            "due": _NULLABLE_STRING,
            "precision": {"anyOf": [{"type": "string", "enum": PRECISIONS}, {"type": "null"}]},
            "issue": {"type": "string", "enum": ISSUES},
            "titleIssue": {"type": "string", "enum": TITLE_ISSUES},
            "confident": {"type": "boolean"},
            "comment": {"type": "string"},
        },
        "required": ["intent", "title", "due", "precision", "issue", "titleIssue", "confident", "comment"],
        "additionalProperties": False,
    }


LABEL_FIELDS = ("intent", "title", "due", "precision", "issue", "titleIssue")


def label_prompt(text: str, now: str) -> str:
    moment = datetime.fromisoformat(now)
    weekday = WEEKDAYS[moment.weekday()]
    return (
        f"Текущий момент: {moment:%Y-%m-%d %H:%M}, {weekday}.\n"
        f"Фраза пользователя (между маркерами, как есть):\n<<<{text}>>>\n\n"
        "Верни разметку JSON-объектом."
    )
