void main() {
  group('NounForms.nominative', () {
    for (final entry in _cases.entries) {
      test('«${entry.key}» → «${entry.value}»', () {
        expect(NounForms.nominative(entry.key), entry.value);
      });
    }

    test('без разрешения предлог не трогается', () {
      expect(
        NounForms.nominative('о встрече', allowPreposition: false),
        'о встрече',
      );
      expect(
        NounForms.nominative('встречу с командой', allowPreposition: false),
        'встреча с командой',
      );
    });

    test('«ё» и регистр пользователя сохраняются', () {
      expect(NounForms.nominative('насчёт отчёта'), 'отчёт');
      expect(NounForms.nominative('ВСТРЕЧУ'), 'ВСТРЕЧУ');
      expect(NounForms.nominative('Планёрку'), 'Планёрка');
    });

    test('пустой и пунктуация', () {
      expect(NounForms.nominative(''), '');
      expect(
        NounForms.nominative('встречу, потом звонок'),
        'встреча, потом звонок',
      );
    });
  });
}
